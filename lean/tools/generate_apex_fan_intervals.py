#!/usr/bin/env python3
"""Propose bounded exact fan coefficients; every enclosure is replayed in Lean.
Input: output of tools/ProposeApexFanRhs.lean (24 rational-expression intervals).
No numeric output is a trusted premise of a theorem.
"""
from pathlib import Path
import argparse,json,re
from generate_family_leaf_example import I,S
ROOT=Path(__file__).resolve().parents[1]
def det3(a):
 return a[0][0]*a[1][1]*a[2][2]-a[0][0]*a[1][2]*a[2][1]-a[0][1]*a[1][0]*a[2][2]+a[0][1]*a[1][2]*a[2][0]+a[0][2]*a[1][0]*a[2][1]-a[0][2]*a[1][1]*a[2][0]
def det4(a):
 d=[det3([[a[i][k]for k in range(4)if k!=j]for i in range(1,4)])for j in range(4)]
 return a[0][0]*d[0]-a[0][1]*d[1]+a[0][2]*d[2]-a[0][3]*d[3]
def vec(xs):return '!['+','.join(xs)+']'
def matrix(xs):return vec([vec([x.lean()for x in row])for row in xs])
def main():
 ap=argparse.ArgumentParser();ap.add_argument('rhs_output',type=Path,nargs='?',help='Lean proposal output; omit to replay the saved JSON rhs');args=ap.parse_args()
 if args.rhs_output is None:
  saved=json.loads((ROOT/'data/apex-fan-interval-proposal.json').read_text())
  pairs=[pair for row in saved['rhs']for pair in row]
 else:
  pairs=re.findall(r'lower := (-?\d+), upper := (-?\d+)',args.rhs_output.read_text())
 if len(pairs)!=24:raise ValueError('Expected exactly 24 RHS intervals')
 rhs=[[I(*map(int,pairs[4*i+j]))for j in range(4)]for i in range(6)]
 src=(ROOT/'SparseLowerTail/Section05/ApexTangencyDeterminant.lean').read_text()
 mattext=src.split('def apexTangencyMatrixIntervals',1)[1].split('theorem',1)[0]
 pairs=re.findall(r'⟨(-?\d+),(-?\d+)⟩',mattext);assert len(pairs)==16
 M=[[I(*map(int,pairs[4*i+j]))for j in range(4)]for i in range(4)]
 D=det4(M);J=D.inv();nums=[[det4([[rhs[i][k]if l==j else M[k][l]for l in range(4)]for k in range(4)])for j in range(4)]for i in range(6)]
 sol=[[n*J for n in row]for row in nums]
 data={'trust_status':'untrusted interval proposals; Lean must check all arithmetic and semantics','scale':S,'rhs':[[[x.l,x.u]for x in row]for row in rhs],'numerators':[[[x.l,x.u]for x in row]for row in nums],'inverse_determinant':[J.l,J.u],'solutions':[[[x.l,x.u]for x in row]for row in sol]}
 (ROOT/'data/apex-fan-interval-proposal.json').write_text(json.dumps(data,indent=2)+'\n')
 s='''import SparseLowerTail.Section05.ApexFanTangency
import SparseLowerTail.Numerics.MatrixSolutionInterval4

/-! Exact enclosures of all 24 solved fan coefficients. Each RHS is checked
against its actual symbolic expression; the common matrix is checked once.
Generated by tools/generate_apex_fan_intervals.py. -/
namespace SparseLowerTail.Section05
open Numerics CoverGeometry
set_option maxRecDepth 100000
set_option maxHeartbeats 8000000

def apexFanRhsIntervals : Fin 6 → Fin 4 → DyadicInterval :=
  '''+matrix(rhs)+'''

theorem apexFanRhsIntervals_checked (i : Fin 6) (j : Fin 4) :
    (apexTangencyRhsExpr (fixedCellThetaQ (i.castAdd 6)) (cellLambdaQ (i.castAdd 6)) j).dyadicEval
       apexPrimitiveIntervals=some (apexFanRhsIntervals i j) := by
  fin_cases i <;> fin_cases j <;> decide +kernel

theorem apexFanRhsIntervals_contains (i : Fin 6) (j : Fin 4) :
    (apexFanRhsIntervals i j).contains
      (-apexTangencyResidual (fun k => (fixedCellThetaQ (i.castAdd 6) k : ℝ))
        (cellLambdaQ (i.castAdd 6) : ℝ) j) := by
  have h := RationalExpr.dyadicEval_contains _ apexPrimitiveIntervals_contains
    (apexFanRhsIntervals_checked i j)
  simpa only [apexTangencyRhsExpr,RationalExpr.realEval_neg,apexResidualExpr_eval] using h

def apexFanNumeratorIntervals : Fin 6 → Fin 4 → DyadicInterval :=
  '''+matrix(nums)+'''

theorem apexFanNumeratorIntervals_checked (i : Fin 6) (j : Fin 4) :
    matrixDetInterval4 (fun k l => if l=j then apexFanRhsIntervals i k
      else apexTangencyMatrixIntervals k l)=some (apexFanNumeratorIntervals i j) := by
  fin_cases i <;> fin_cases j <;> decide +kernel

def apexFanInverseDetInterval : DyadicInterval := '''+J.lean()+'''

theorem apexFanInverseDetInterval_checked :
    apexTangencyDetInterval.inv?=some apexFanInverseDetInterval := by decide +kernel

def apexFanSolutionIntervals : Fin 6 → Fin 4 → DyadicInterval :=
  '''+matrix(sol)+'''

theorem apexFanSolutionIntervals_checked (i : Fin 6) (j : Fin 4) :
    (apexFanNumeratorIntervals i j).mul apexFanInverseDetInterval=apexFanSolutionIntervals i j := by
  fin_cases i <;> fin_cases j <;> decide +kernel

theorem apexFanSolutionIntervals_contains (i : Fin 6) (j : Fin 4) :
    (apexFanSolutionIntervals i j).contains
      ((apexSolutionExpr (fixedCellThetaQ (i.castAdd 6)) (cellLambdaQ (i.castAdd 6)) j).realEval
         apexPrimitiveValues) := by
  have hs := RationalExpr.cramer4_solves apexTangencyMatrixExpr
    (apexTangencyRhsExpr (fixedCellThetaQ (i.castAdd 6)) (cellLambdaQ (i.castAdd 6)))
    apexPrimitiveValues (by simpa only [apexTangencyMatrixExpr_eval] using apexTangencyMatrix_det_ne_zero)
  simp only [apexTangencyMatrixExpr_eval,apexTangencyRhsExpr_eval] at hs
  rw [←apexFanSolutionIntervals_checked]
  exact matrixSolution4_interval apexTangencyMatrixIntervals_contains
    (apexFanRhsIntervals_contains i) apexTangencyDetInterval_checked
    apexTangencyDetInterval_apart apexFanInverseDetInterval_checked hs j
    (apexFanNumeratorIntervals_checked i j)

def apexFanCoefficientIntervals (i : Fin 6) : Fin 12 → DyadicInterval :=
  ![apexFanSolutionIntervals i 0,DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 1),
    apexFanSolutionIntervals i 1,apexFanSolutionIntervals i 2,apexFanSolutionIntervals i 3,
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 5),
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 6),
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 7),
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 8),
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 9),
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 10),
    DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) 11)]

theorem apexFanCoefficientIntervals_contains (i : Fin 6) (j : Fin 12) :
    (apexFanCoefficientIntervals i j).contains (apexFanTheta i j) := by
  fin_cases j
'''
 for k in range(12):
  if k in [0,2,3,4]:
   j=[0,2,3,4].index(k)
   s+=f'''  · change (apexFanSolutionIntervals i {j}).contains (apexFanTheta i (apexUnknownIndex {j}))
    rw [apexFanTheta_unknown]
    exact apexFanSolutionIntervals_contains i {j}
'''
  else:
   s+=f'''  · change (DyadicInterval.point (fixedCellThetaQ (i.castAdd 6) {k})).contains (apexFanTheta i {k})
    rw [apexFanTheta_fixed i {k} (by decide) (by decide) (by decide) (by decide)]
    exact DyadicInterval.point_contains _
'''
 s+='\nend SparseLowerTail.Section05\n'
 (ROOT/'SparseLowerTail/Section05/ApexFanIntervals.lean').write_text(s)
 for i,row in enumerate(sol):print('F'+str(i+1),[(x.l/S,x.u/S)for x in row])
if __name__=='__main__':main()
