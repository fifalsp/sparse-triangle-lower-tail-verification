#!/usr/bin/env python3
"""Refined matrix/RHS/Cramer proposals. Lean checks every interval operation.
Input: the 40 intervals printed by tools/ProposeRefinedApexSystem.lean.
Omit the input path to regenerate from the recorded proposals.
"""
from pathlib import Path
import argparse,json,re
from generate_family_leaf_example import I,S
from generate_apex_fan_intervals import det4,matrix
ROOT=Path(__file__).resolve().parents[1]
def definition(text,name,value):
 pattern=r'(def '+re.escape(name)+r'\b[\s\S]*?:=)[\s\S]*?(?=\n\n(?:theorem|def))'
 text,n=re.subn(pattern,lambda m:m[1]+'\n  '+value,text,count=1)
 if n!=1:raise ValueError('Missing unique definition '+name)
 return text

def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('output',nargs='?',type=Path);args=ap.parse_args()
 path=ROOT/'data/apex-refined-system-proposal.json'
 if args.output:
  pairs=re.findall(r'lower := (-?\d+), upper := (-?\d+)',args.output.read_text())
  if len(pairs)!=40:raise ValueError(f'Expected 40 intervals, found {len(pairs)}')
  M=[[I(*map(int,pairs[4*i+j]))for j in range(4)]for i in range(4)]
  rhs=[[I(*map(int,pairs[16+4*i+j]))for j in range(4)]for i in range(6)]
 else:
  data=json.loads(path.read_text());M=[[I(*v)for v in row]for row in data['matrix']];rhs=[[I(*v)for v in row]for row in data['rhs']]
 D=det4(M);J=D.inv()
 nums=[[det4([[rhs[i][k]if l==j else M[k][l]for l in range(4)]for k in range(4)])for j in range(4)]for i in range(6)]
 sol=[[v*J for v in row]for row in nums]
 data={'trust_status':'untrusted proposals; all enclosures require Lean kernel verification','scale':S,'matrix':[[[v.l,v.u]for v in row]for row in M],'rhs':[[[v.l,v.u]for v in row]for row in rhs],'solutions':[[[v.l,v.u]for v in row]for row in sol]}
 path.write_text(json.dumps(data,indent=2)+'\n')
 def refine(text):
  return text.replace('namespace SparseLowerTail.Section05\n','namespace SparseLowerTail.Section05.RefinedApex\n').replace('end SparseLowerTail.Section05\n','end SparseLowerTail.Section05.RefinedApex\n').replace('apexPrimitiveIntervals','apexRefinedPrimitiveIntervals')
 s=(ROOT/'SparseLowerTail/Section05/ApexTangencyDeterminant.lean').read_text()
 s=refine(s.replace('import SparseLowerTail.Section05.ApexPrimitiveIntervals','import SparseLowerTail.Section05.ApexRefinedPrimitives'))
 s=definition(s,'apexTangencyMatrixIntervals',matrix(M))
 s=definition(s,'apexTangencyDetInterval',D.lean())
 (ROOT/'SparseLowerTail/Section05/ApexRefinedSystem.lean').write_text(s)
 s=(ROOT/'SparseLowerTail/Section05/ApexFanIntervals.lean').read_text()
 s=refine(s.replace('import SparseLowerTail.Section05.ApexFanTangency','import SparseLowerTail.Section05.ApexFanTangency\nimport SparseLowerTail.Section05.ApexRefinedSystem'))
 s=s.replace('Generated by tools/generate_apex_fan_intervals.py.', 'Generated by tools/generate_refined_apex_intervals.py.')
 for name,value in [('apexFanRhsIntervals',matrix(rhs)),('apexFanNumeratorIntervals',matrix(nums)),('apexFanInverseDetInterval',J.lean()),('apexFanSolutionIntervals',matrix(sol))]:s=definition(s,name,value)
 (ROOT/'SparseLowerTail/Section05/ApexRefinedFanIntervals.lean').write_text(s)
 for i,row in enumerate(sol):print(f'F{i+1} coefficient widths:',[(v.u-v.l)/S for v in row])
if __name__=='__main__':main()
